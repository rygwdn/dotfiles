import { mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { extensionFingerprint } from "./extension-bundle";
const result = await Bun.build({
  entrypoints: ["./omp-extension.ts"], target: "bun", format: "esm", minify: true,
  external: ["@oh-my-pi/pi-coding-agent/config/registry"],
});
if (!result.success) throw new AggregateError(result.logs, "OMP extension build failed");
const source = `// continuity-source-sha256: ${extensionFingerprint(fileURLToPath(new URL(".", import.meta.url)))}\n${await result.outputs[0]!.text()}`;
await mkdir("generated", { recursive: true });
await Bun.write("generated/omp-extension.mjs", source);
await Bun.write("generated/extension-source.ts", `// Generated by bun run bundle-extension.ts; regenerate after runtime changes.\nexport const extensionSource = ${JSON.stringify(source)};\n`);
console.log(`Bundled OMP extension (${Buffer.byteLength(source)} bytes).`);
