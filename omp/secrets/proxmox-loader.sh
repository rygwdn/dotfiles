#!/bin/bash
# omp-secrets — bridge between the SOPS+age encrypted secret store and
# consumers on this host without writing decrypted plaintext to persistent disk.
# Nested objects are ignored by shell/systemd environment output; only top-level
# string entries are exported or materialized.
set -euo pipefail

STORE=/root/.secrets/omp-tokens.yaml
SOPS_CFG=/root/.secrets/.sops.yaml
RUNDIR=/run/omp-secrets
export SOPS_AGE_KEY_FILE=/root/.config/sops/age/keys.txt
sops() { command sops --config "$SOPS_CFG" "$@"; }

declare -A MATERIALIZE_MAP=(
	[OMADA_CFG_CONTENT]="omada.cfg"
)

sync_obfuscation() {
	install -d -m 700 "$RUNDIR" /root/.omp/agent
	tmp="$RUNDIR/secrets.yml.tmp"
	{
		echo "# Generated by omp-secrets sync-obfuscation — do not edit by hand."
		echo "# Regenerate after changing $STORE."
		sops -d --output-type json "$STORE" |
			python3 -c '
import json, sys
data = json.load(sys.stdin)
if not isinstance(data, dict):
    raise ValueError("secret store must be an object")
for key, value in data.items():
    if key == "EXAMPLE_TOKEN" or key.endswith("_CONTENT") or not isinstance(value, str) or len(value) < 8:
        continue
    print("- type: plain")
    print(f"  content: {json.dumps(value)}")
    print(f"  friendlyName: {key}")
'
	} >"$tmp"
	chmod 600 "$tmp"
	mv -f "$tmp" "$RUNDIR/secrets.yml"
	ln -sfn "$RUNDIR/secrets.yml" /root/.omp/agent/secrets.yml
}

usage() {
	echo "usage: omp-secrets {edit|env [bash|fish]|load|sync-obfuscation}" >&2
	exit 1
}

[ $# -ge 1 ] || usage

case "$1" in
edit)
	sops "$STORE"
	;;
env)
	shell="${2:-bash}"
	case "$shell" in
	bash|fish)
		sops -d --output-type json "$STORE" |
			python3 -c '
import json, re, shlex, sys
data = json.load(sys.stdin)
if not isinstance(data, dict):
    raise ValueError("secret store must be an object")
shell = sys.argv[1]
for key, value in data.items():
    if (not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", key)
            or key == "EXAMPLE_TOKEN" or key.endswith("_CONTENT")
            or not isinstance(value, str)):
        continue
    quoted = shlex.quote(value)
    if shell == "bash":
        print(f"export {key}={quoted}")
    else:
        print(f"set -gx {key} {quoted}")
' "$shell"
		;;
	*)
		usage
		;;
	esac
	;;
load)
	install -d -m 700 "$RUNDIR"
	umask 077
	sops -d --output-type json "$STORE" |
		python3 -c '
import json, re, sys
data = json.load(sys.stdin)
if not isinstance(data, dict):
    raise ValueError("secret store must be an object")
for key, value in data.items():
    if (not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", key)
            or key == "EXAMPLE_TOKEN" or key.endswith("_CONTENT")
            or not isinstance(value, str)):
        continue
    # systemd EnvironmentFile accepts quoted values across physical lines.
    # Preserve newlines and escape only syntax-significant backslashes/quotes.
    escaped = value.replace("\\", "\\\\").replace("\"", "\\\"")
    sys.stdout.write(f"{key}=\"{escaped}\"\n")
' >"$RUNDIR/env"
	chmod 600 "$RUNDIR/env"
	for key in "${!MATERIALIZE_MAP[@]}"; do
		target="$RUNDIR/${MATERIALIZE_MAP[$key]}"
		sops -d --output-type json "$STORE" |
			python3 -c "
import json, sys
data = json.load(sys.stdin)
if not isinstance(data, dict):
    raise ValueError('secret store must be an object')
value = data.get('$key')
if isinstance(value, str):
    sys.stdout.write(value)
" >"$target"
		chmod 600 "$target"
	done
	sync_obfuscation
	echo "$RUNDIR/env"
	;;
sync-obfuscation)
	sync_obfuscation
	echo "wrote /root/.omp/agent/secrets.yml -> $RUNDIR/secrets.yml (tmpfs)"
	;;
*)
	usage
	;;
esac
